unhex :: String -> BS.ByteString
unhex (a : b : t) = BS.cons (fromIntegral (digitToInt a * 16 + digitToInt b)) (unhex t)
unhex _ = BS.empty

pngFixture :: String -> (BS.ByteString, BS.ByteString, BS.ByteString)
pngFixture wanted = case [ (unhex f, unhex c, unhex a) | (n, f, c, a) <- pngFixtures, n == wanted ] of
  r : _ -> r
  [] -> error ("no PNG fixture " ++ wanted)

-- The data of the first chunk of a PNG file with this type
pngChunk :: String -> BS.ByteString -> BS.ByteString
pngChunk name file =
  let (before, rest) = BS.breakSubstring (C.pack name) file
      len = BS.foldl' (\a w -> a * 256 + fromIntegral w) 0 (BS.drop (BS.length before - 4) before) :: Int
  in BS.take len (BS.drop 4 rest)

-- Replace the data of the first chunk with this type. The check value of
-- the chunk is not changed: the parser does not verify it.
withPngChunk :: String -> BS.ByteString -> BS.ByteString -> BS.ByteString
withPngChunk name body file =
  let (before, rest) = BS.breakSubstring (C.pack name) file
      old = pngChunk name file
      be32 n = BS.pack [ fromIntegral (n `div` (256 ^ k)) | k <- [3, 2, 1, 0 :: Int] ]
  in BS.concat [ BS.take (BS.length before - 4) before, be32 (BS.length body), C.pack name, body
               , BS.drop (4 + BS.length old) rest ]

-- The image objects of a document: the dictionary and the data of each one
imageStreams :: BS.ByteString -> [(BS.ByteString, BS.ByteString)]
imageStreams pdf = go pdf
  where
    marker = C.pack "\nstream\n"
    -- the text after the last " obj"
    last_object b = case BS.breakSubstring (C.pack " obj\n") b of
      (_, r) | BS.null r -> b
             | otherwise -> last_object (BS.drop 5 r)
    go s = case BS.breakSubstring marker s of
      (_, r) | BS.null r -> []
      (before, r) ->
        let dict = last_object before
            (body, after) = BS.breakSubstring (C.pack "\nendstream") (BS.drop (BS.length marker) r)
            others = go after
        in if C.pack "/Subtype /Image" `BS.isInfixOf` dict then (dict, body) : others else others

-- A document with one PNG image
pngDocument :: PngFile -> BS.ByteString
pngDocument png = BL.toStrict $ renderPdf standardDocInfo (PDFRect 0 0 100 100) $ do
  image <- createPDFPng png
  page <- addPage Nothing
  drawWithPage page (drawXObject image)

-- A PNG image goes to the document with its pixels and its transparency.
-- See Note [PNG images] in Graphics.PDF.LowLevel.PNG
test_pngImages :: IO ()
test_pngImages = do
  let inflate = BL.toStrict . Zlib.decompress . BL.fromStrict
      images name = case parsePng file of
          Left e -> error (name ++ ": " ++ e)
          Right png -> (file, colours, alphas, pngBounds png, imageStreams (pngDocument png))
        where (file, colours, alphas) = pngFixture name
      has dict x = assertBoolVerbose (x ++ " in " ++ C.unpack dict) (C.pack x `BS.isInfixOf` dict)
      hasNot dict x = assertBoolVerbose (x ++ " not in " ++ C.unpack dict) (not (C.pack x `BS.isInfixOf` dict))
      -- the pixels of the file go to the document as they are
      passThrough name entries = case images name of
        (file, _, _, size, [(dict, body)]) -> do
          assertEqual (5, 3) size
          assertEqual (pngChunk "IDAT" file) body
          mapM_ (has dict) (["/Predictor 15", "/Columns 5", "/Width 5", "/Height 3", "/Filter /FlateDecode"] ++ entries)
          hasNot dict "/SMask"
        _ -> assertFailure (name ++ ": expected one image")
      -- the pixels are decoded: the colours, and the alpha as a second image
      decoded name height entries = case images name of
        (_, colours, alphas, _, streams) -> do
          let mains = [ s | s@(d, _) <- streams, BS.null alphas || C.pack "/SMask" `BS.isInfixOf` d ]
              masks = [ s | s@(d, _) <- streams, not (C.pack "/SMask" `BS.isInfixOf` d), not (BS.null alphas) ]
          case mains of
            [(dict, body)] -> do
              assertEqual colours (inflate body)
              mapM_ (has dict) entries
              hasNot dict "/Predictor"
            _ -> assertFailure (name ++ ": expected one image with the colours")
          if BS.null alphas
            then assertEqual 1 (length streams)
            else case masks of
              [(dict, body)] -> do
                assertEqual alphas (inflate body)
                mapM_ (has dict) ["/ColorSpace /DeviceGray", "/BitsPerComponent 8", "/Width 5", "/Height " ++ show (height :: Int)]
              _ -> assertFailure (name ++ ": expected one image with the alpha")
  passThrough "rgb8" ["/ColorSpace /DeviceRGB", "/Colors 3", "/BitsPerComponent 8"]
  passThrough "gray1" ["/ColorSpace /DeviceGray", "/Colors 1", "/BitsPerComponent 1"]
  passThrough "rgb8_key" ["/Mask [1 1 2 2 3 3 ]"]
  decoded "rgba8" 3 ["/ColorSpace /DeviceRGB", "/BitsPerComponent 8", "/SMask"]
  decoded "graya8" 3 ["/ColorSpace /DeviceGray", "/BitsPerComponent 8", "/SMask"]
  decoded "rgb8_interlaced" 3 ["/ColorSpace /DeviceRGB", "/BitsPerComponent 8"]
  decoded "palette2_alpha" 3 ["/Indexed /DeviceRGB 3 <0A141EC8643200FF00FFFFFF>", "/BitsPerComponent 2", "/SMask"]
  -- the lines of this file have the filters 1, 2, 3, 4 and 0
  decoded "rgba8_filters" 5 ["/ColorSpace /DeviceRGB", "/Height 5", "/SMask"]
  -- each pass of this interlaced file has another filter
  decoded "palette8_alpha_interlaced" 3 ["/Indexed /DeviceRGB 3 <0A141EC8643200FF00FFFFFF>", "/BitsPerComponent 8", "/SMask"]

-- A file that is not a correct PNG file gives Left, and never an exception.
test_pngMalformed :: IO ()
test_pngMalformed = do
  let files = [ unhex f | (_, f, _, _) <- pngFixtures ]
      (rgb, _, _) = pngFixture "rgb8"
      isLeft = either (const True) (const False)
      -- the result, with the bytes of a document if the file is accepted
      outcome file = case parsePng file of
        Left e -> length e
        Right png -> BS.length (pngDocument png)
      deflate = BL.toStrict . Zlib.compress . BL.fromStrict
  -- the file is cut at each position
  mapM_ (\file -> mapM_ (\n -> assertBool (isLeft (parsePng (BS.take n file)))) [0 .. BS.length file - 13]) files
  -- each byte is changed: no exception
  mapM_ (\file -> mapM_ (\i -> do
           let changed = BS.concat [BS.take i file, BS.singleton (BS.index file i `xor` 0xFF), BS.drop (i + 1) file]
           n <- evaluate (outcome changed)
           assertBool (n >= 0))
         [0 .. BS.length file - 1]) files
  assertBool (isLeft (parsePng BS.empty))
  assertBool (isLeft (parsePng (C.pack "not a PNG file")))
  -- the data is longer or shorter than the header gives
  assertBool (isLeft (parsePng (withPngChunk "IDAT" (deflate (BS.replicate 1000000 0)) rgb)))
  assertBool (isLeft (parsePng (withPngChunk "IDAT" (deflate (BS.replicate 47 0)) rgb)))
  assertBool (isLeft (parsePng (withPngChunk "IDAT" (deflate BS.empty) rgb)))
  -- 48 bytes are 3 lines of 1 + 15 bytes: a filter byte of 0 is accepted, 5 is not
  assertBool (not (isLeft (parsePng (withPngChunk "IDAT" (deflate (BS.replicate 48 0)) rgb))))
  assertBool (isLeft (parsePng (withPngChunk "IDAT" (deflate (BS.replicate 48 5)) rgb)))
  -- a header with a size, a number of bits or a colour type that is not possible
  let header w h bits ctype = BS.pack ([0, 0, 0, w, 0, 0, 0, h, bits, ctype, 0, 0, 0])
  mapM_ (\ihdr -> assertBool (isLeft (parsePng (withPngChunk "IHDR" ihdr rgb))))
        [header 0 3 8 2, header 5 0 8 2, header 5 3 3 2, header 5 3 8 5, header 5 3 4 2, header 5 3 16 3]
